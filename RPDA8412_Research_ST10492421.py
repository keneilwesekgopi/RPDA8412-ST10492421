def plot_confusion(preds, title):
    cm = confusion_matrix(y_true, preds, labels=np.arange(num_tag_1))
    cm_norm = cm / cm.sum(axis=1, keepdims=True).clip(min=1)   # each row sums to 1 -> per-class recall

    size = max(7, num_tag_1 * 0.6)
    fig, axes = plt.subplots(1, 2, figsize=(size * 2, size))
    annotate = num_tag_1 <= 15                                  # skip numbers if too crowded

    sns.heatmap(cm, annot=annotate, fmt='d', cmap='Blues',
                xticklabels=class_names, yticklabels=class_names, ax=axes[0])
    axes[0].set_title(f'{title}: counts')

    sns.heatmap(cm_norm, annot=annotate, fmt='.2f', cmap='Blues', vmin=0, vmax=1,
                xticklabels=class_names, yticklabels=class_names, ax=axes[1])
    axes[1].set_title(f'{title}: normalised by true class')

    for ax in axes:
        ax.set_xlabel('Predicted')
        ax.set_ylabel('True')
        ax.tick_params(axis='x', rotation=45)
    plt.tight_layout()
    plt.show()
    return cm

