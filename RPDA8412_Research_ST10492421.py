def preprocess_text(text):
    text = text.lower()                                              # change text to lower case
    text = re.sub(r'\[.*?\]', '', text)                              # remove text in square brackets
    text = re.sub(r'https?://\S+\s*', '', text)                      # remove links
    text = re.sub(r'<.*?>', '', text)                                # remove html tags
    text = re.sub(r"['’]", '', text)                                 # don't -> dont (new)
    text = re.sub(f"[{re.escape(string.punctuation)}]", ' ', text)   # punctuation -> space (was '')
    text = re.sub(r'\s+', ' ', text).strip()                         # newlines/tabs/extra spaces -> one space (replaces the \n line)
    return text

